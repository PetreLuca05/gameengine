static float table_cd(const float (*t)[2], int n, float m) {
    if (m <= t[0][0]) return t[0][1];
    if (m >= t[n - 1][0]) return t[n - 1][1];
    // Binary search: the tables are sorted by Mach.
    int lo = 0, hi = n - 1;
    while (hi - lo > 1) {
        int mid = (lo + hi) >> 1;
        if (t[mid][0] <= m) lo = mid; else hi = mid;
    }
    float f = (m - t[lo][0]) / (t[hi][0] - t[lo][0]);
    return t[lo][1] + (t[hi][1] - t[lo][1]) * f;
}

float bal_drag_cd(int curve, float mach) {
    switch (curve) {
    case BAL_CURVE_G7: return table_cd(k_g7, ARRAY_COUNT(k_g7), mach);
    case BAL_CURVE_GS: return table_cd(k_gs, ARRAY_COUNT(k_gs), mach);
    default: return table_cd(k_g1, ARRAY_COUNT(k_g1), mach);
    }
}

float bal_drag_decel(int curve, float bc, float speed, float rho, float sound_speed) {
    if (bc <= 0.0f || speed <= 0.0f) return 0.0f;
    float cd = bal_drag_cd(curve, speed / sound_speed);
    return rho * cd * speed * speed * (3.14159265f / 8.0f) / (bc * BAL_BC_SI);
}
