#!/usr/bin/env python3
"""Reference trajectories for tests/test_ballistics.c (docs/BALLISTICS.md "Tests").

Solves the same cartridges with py-ballisticcalc (an independent LGPL point-mass solver with the
standard G1 / G7 tables, https://github.com/o-murphy/py-ballisticcalc) in the ICAO standard
atmosphere (15 C, 1013.25 hPa, dry), no zero (bore line), no spin drift, and writes velocity,
drop, time of flight and the drift in a 5 m/s full-value crosswind at 25 / 100 / 300 / 500 m to
tests/data/ballistics_ref.json.

    pip install py-ballisticcalc
    python tools/ballistics_ref.py
"""
import json, os, sys

try:
    from py_ballisticcalc import (Ammo, Atmo, Calculator, DragModel, Shot, TableG1, TableG7, Unit,
                                  Weapon, Wind)
except ImportError:
    sys.exit("needs py-ballisticcalc (pip install py-ballisticcalc)")

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
with open(os.path.join(ROOT, "assets", "ballistics", "cartridges.json")) as _f:
    CARTS = json.load(_f)["cartridges"]
CASES = [("556_m855", 900.0), ("762x51_m80", 850.0), ("9x19_fmj", 360.0), ("762x39_m43", 720.0)]
RANGES = [25, 100, 300, 500]
WIND = 5.0


def solve(cart, mv, wind):
    table = {"g1": TableG1, "g7": TableG7}[cart["drag"]]
    dm = DragModel(cart["bc"], table, Unit.Gram(cart["mass_g"]), Unit.Millimeter(cart["diameter_mm"]),
                   Unit.Millimeter(cart["length_mm"]))
    ammo = Ammo(dm, Unit.MPS(mv))
    winds = [Wind(Unit.MPS(wind), Unit.Degree(90), Unit.Meter(5000))] if wind else None
    shot = Shot(ammo=ammo, atmo=Atmo.icao(), weapon=Weapon(sight_height=Unit.Meter(0)), winds=winds)
    res = Calculator().fire(shot, Unit.Meter(max(RANGES) + 10), Unit.Meter(5), raise_range_error=False)
    out = {}
    for r in RANGES:
        row = res.get_at("distance", Unit.Meter(r))
        out[str(r)] = {
            "v": row.velocity >> Unit.MPS,
            "drop": -(row.height >> Unit.Meter),
            "t": row.time,
            "drift": abs(row.windage >> Unit.Meter),
        }
    return out


def main():
    ref = {"_comment": "Generated by tools/ballistics_ref.py (py-ballisticcalc, ICAO atmosphere, bore line, "
                       "no spin drift; drift = |windage| in a 5 m/s full-value crosswind).", "cases": []}
    for cid, mv in CASES:
        cart = next(c for c in CARTS if c["id"] == cid)
        still = solve(cart, mv, 0.0)
        windy = solve(cart, mv, WIND)
        for r in RANGES:
            still[str(r)]["drift"] = windy[str(r)]["drift"]
        ref["cases"].append({"cartridge": cid, "mv": mv, "points": still})
    path = os.path.join(ROOT, "tests", "data", "ballistics_ref.json")
    with open(path, "w", newline="\n") as f:
        json.dump(ref, f, indent=2)
        f.write("\n")
    for c in ref["cases"]:
        print(c["cartridge"], {k: {kk: round(vv, 3) for kk, vv in v.items()} for k, v in c["points"].items()})


if __name__ == "__main__":
    main()
