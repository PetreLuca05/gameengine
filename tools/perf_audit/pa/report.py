"""Reports: the audit Markdown (ranked table + details), the machine-readable JSON, the findings registry
(docs/perf/FINDINGS.md)."""
import json
import os

from .findings import ranked
from .profile import median, pct, mean


def fmt_savings(s):
    parts = []
    if s.get("cpu_ms"):
        parts.append("%.3f ms CPU" % s["cpu_ms"])
    if s.get("gpu_ms"):
        parts.append("%.3f ms GPU" % s["gpu_ms"])
    if s.get("mb"):
        parts.append("%.1f MB" % s["mb"])
    if s.get("bytes_s"):
        parts.append("%.1f kB/s" % (s["bytes_s"] / 1024.0))
    return ", ".join(parts) or "n/a"


def scene_table(profiles):
    from .verify import cpu_work
    rows = []
    for p in sorted(profiles, key=lambda p: (p.scene, p.fidelity)):
        cw = cpu_work(p)
        g = p.gpu_frame_ms()
        rows.append("| %s | %s | %d | %.2f / %.2f | %.2f / %.2f | %.2f | %.0f | %.0f | %.0f | %.0f |" % (
            p.scene, p.fidelity, p.frames, median(cw), pct(cw, 95), median(g), pct(g, 95), median(p.cpu_ms()),
            p.counter_mean("alloc_count"), p.counter_mean("draw_items"), mean(p.series("vram_usage_mb")), mean(p.series("process_mb"))))
    head = ("| Scene | Fidelity | Frames | CPU work ms p50 / p95 | GPU ms p50 / p95 | Frame ms p50 | Allocs / frame | Draw items | VRAM MB | Process MB |\n"
            "|---|---|---|---|---|---|---|---|---|---|")
    return head + "\n" + "\n".join(rows)


def findings_table(fs, n=None, status=None):
    rows = ["| # | Id | Rule | Finding | Est. savings | Confidence | Effort | Fix | Status |", "|---|---|---|---|---|---|---|---|---|"]
    for i, f in enumerate(fs[:n] if n else fs, 1):
        st = (status or {}).get(f.id) or (("implemented %s" % f.fix_id) if f.fix_id else "open")
        rows.append("| %d | %s | %s | %s | %s | %s | %s | %s | %s |" % (
            i, f.id, f.rule, f.title.replace("|", "/"), fmt_savings(f.savings) + (" (below noise)" if f.below_noise else ""), f.confidence, f.effort,
            f.fix_id or "-", st))
    return "\n".join(rows)


def detail(f):
    loc = ", ".join("%s `%s`" % (k, v) for k, v in f.location.items() if v not in (None, ""))
    ev = json.dumps(f.evidence, sort_keys=True)
    if len(ev) > 900:
        ev = ev[:900] + " ..."
    return ("### %s %s: %s\n\n- Location: %s (%s)\n- Evidence: `%s`\n- Scenes: %s\n- Estimated savings: %s\n- Confidence: %s; effort: %s; source: %s\n"
            "- Fidelity impact: **%s**; verification: %s\n- Suggested fix: %s\n") % (
        f.id, f.rule, f.title, loc or "-", f.system, ev, ", ".join(f.scenes) or "-", fmt_savings(f.savings), f.confidence, f.effort, f.source,
        f.fidelity, f.verify, f.fix)


def write_audit(path_md, path_json, findings, profiles, meta, notes=None, status=None, top=25, registry=None):
    main = ranked([f for f in findings if f.fidelity == "none" and f.rule != "R00"])
    trade = ranked([f for f in findings if f.fidelity == "tradeoff"])
    info = [f for f in findings if f.fidelity == "info"]
    errors = [f for f in findings if f.rule == "R00"]
    lines = ["# Performance audit %s" % meta.get("date", ""), ""]
    lines.append("Generated by `tools/perf_audit/perf_audit.py analyze` (methodology, rules and how to close a finding: "
                 "[docs/PERF_AUDIT.md](../PERF_AUDIT.md); finding status: [FINDINGS.md](FINDINGS.md)).")
    lines.append("")
    for n in notes or []:
        lines.append("> " + n)
        lines.append(">")
    if notes:
        lines.append("")
    if profiles:
        lines += ["## Scenes", "", scene_table(profiles), ""]
    lines += ["## Top %d fidelity-neutral findings" % min(top, len(main)), "",
              "Ranked by estimated savings x confidence / effort (S 1, M 3, L 8). Fidelity impact is **none** for every row: the fix keeps the "
              "image and the gameplay state identical (proved per finding by `perf_verify`: image diff + state hash).", "",
              findings_table(main, top, status), ""]
    if registry:
        lines += ["## Fixes implemented (fidelity-neutral, behind perf_fix_disable)", "",
                  "| Fix | Title | Status | Latest perf_verify |", "|---|---|---|---|"]
        for fid, e in sorted(registry.items()):
            if fid.startswith("_"):
                continue
            v = e.get("verification") or {}
            lines.append("| %s | %s | %s | %s |" % (fid, e.get("title", ""), e.get("status", ""), (v.get("summary") or "-").replace("|", "/")))
        lines.append("")
    lines += ["## Details", ""]
    for f in main[:top]:
        lines.append(detail(f))
    if len(main) > top:
        lines += ["## Further fidelity-neutral findings", "", findings_table(main[top:], None, status), ""]
    lines += ["## Trade-off opportunities (quality-affecting, NOT recommended)", "",
              "These would save time or memory by changing the image (resolution, sample counts, compression, precision). They are the "
              "Engine Fidelity tables' job, not this audit's; listed for completeness only.", ""]
    rows = ["| Id | Rule | Opportunity | Est. savings | Why not |", "|---|---|---|---|---|"]
    for f in trade[:20]:
        rows.append("| %s | %s | %s | %s | %s |" % (f.id, f.rule, f.title.replace("|", "/"), fmt_savings(f.savings), f.fix.replace("|", "/")))
    lines += ["\n".join(rows), ""]
    if info:
        lines += ["## Classifications (no action by themselves)", ""] + ["- %s %s: %s" % (f.id, f.rule, f.title) for f in info] + [""]
    if errors:
        lines += ["## Rule errors", ""] + ["- %s" % f.title for f in errors] + [""]
    with open(path_md, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines))
    with open(path_json, "w", encoding="utf-8", newline="\n") as fh:
        json.dump({"meta": meta, "profiles": [p.path.replace("\\", "/") for p in profiles], "findings": [f.to_dict() for f in main],
                   "tradeoffs": [f.to_dict() for f in trade], "errors": [f.to_dict() for f in errors]}, fh, indent=1)
    return main, trade


def write_findings_md(path, registry):
    """docs/perf/FINDINGS.md from docs/perf/fixes.json."""
    lines = ["# Tracked performance findings", "",
             "Generated from `docs/perf/fixes.json` by `tools/perf_audit/perf_audit.py findings`. A finding is **closed** only when "
             "`perf_verify` showed the timing improvement AND every reference image pair passed AND the gameplay state hashes matched "
             "(docs/PERF_AUDIT.md \"Closing a finding\"). Fixes are switched off for A/B runs with `perf_fix_disable <id>`.", "",
             "| Fix | Finding | Title | Status | Effort | Verified on | Result |", "|---|---|---|---|---|---|---|"]
    for fid, f in sorted(registry.items()):
        if fid.startswith("_"):
            continue
        v = f.get("verification") or {}
        res = v.get("summary", "-")
        lines.append("| %s | %s | %s | %s | %s | %s | %s |" % (fid, f.get("finding", "-"), f.get("title", ""), f.get("status", "open"), f.get("effort", "-"),
                                                          v.get("machine", "-"), res.replace("|", "/")))
    lines.append("")
    for fid, f in sorted(registry.items()):
        if fid.startswith("_"):
            continue
        lines += ["## %s: %s" % (fid, f.get("title", "")), "", f.get("description", ""), "",
                  "- Rule / finding: %s %s" % (f.get("rule", "-"), f.get("finding", "-")),
                  "- Code: %s" % ", ".join("`%s`" % c for c in f.get("code", [])),
                  "- Metrics (perf_verify): %s" % ", ".join("`%s`" % m for m in f.get("metrics", [])),
                  "- Scenes: %s" % ", ".join(f.get("scenes", [])),
                  "- Why fidelity-neutral: %s" % f.get("neutral", "-"), ""]
        for run in (f.get("verification") or {}).get("runs", []):
            lines.append("- Verification run (%s, %s): %s" % (run.get("machine", "?"), run.get("date", "?"), run.get("summary", "")))
        lines.append("")
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines))
