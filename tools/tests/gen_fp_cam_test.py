"""Writes tools/tests/fp_cam_test.cfg: a scripted locomotion run (walk, sprint, crouch, jump,
mantle, a full 360 deg turn, every weapon, ADS each) recorded by `fp_cam_test`, which asserts
every frame: |camera - head bone| < 0.15 m, camera forward . (camera - pelvis) >= 0 (never behind
the body) and both hands on their item sockets (< 2 mm / 1 deg). Run:
  deadground.exe --test --script tools/tests/fp_cam_test.cfg   ->  "fp_cam_test: ... PASS"
"""
import os

L = ['// generated by gen_fp_cam_test.py', 'set cam_debug 0', 'wait 40']
weapons = ['rifle', 'pistol', 'shotgun', 'smg', 'lmg', 'dmr', 'sniper', 'crossbow']
for w in weapons:
    L.append('give %s' % w)
L += ['slot 1', 'wait 30', 'setpos 0 0.05 22 0 0', 'wait 30', 'fp_cam_test start']
# Walk, strafe, sprint.
L += ['+forward', 'wait 60', '+left', 'wait 30', '-left', '+sprint', 'wait 60', '-sprint', '-forward']
# Full 360 turn while walking.
L += ['+forward']
for i in range(36):
    L += ['setang %d -5' % (i * 10), 'wait 2']
L += ['-forward', 'setang 0 0']
# Crouch walk, look down / up.
L += ['+crouch', '+forward', 'wait 50', '-forward', 'setang 0 -60', 'wait 20', 'setang 0 50', 'wait 20', '-crouch', 'setang 0 0', 'wait 20']
# Jumps.
L += ['+forward', '+jump', 'wait 4', '-jump', 'wait 50', '+jump', 'wait 4', '-jump', 'wait 50', '-forward']
# Mantle the 1.0 m box (dev room: x -6, z -18).
L += ['setpos -6 0.05 -15.2 0 -10', 'wait 20', '+forward', 'wait 25', '+jump', 'wait 4', '-jump', 'wait 70', '-forward', 'wait 20']
# Every weapon: hip, ADS, hip.
L += ['setpos 0 0.05 22 0 0', 'wait 20']
for i, w in enumerate(weapons):
    L += ['slot %d' % (i + 1), 'wait 45', '+aim', 'wait 40', 'setang 20 10', 'wait 15', 'setang 0 0', 'wait 10', '-aim', 'wait 25']
L += ['fp_cam_test report', 'wait 2', 'quit']
here = os.path.dirname(os.path.abspath(__file__))
with open(os.path.join(here, 'fp_cam_test.cfg'), 'w', newline='\n') as f:
    f.write('\n'.join(L) + '\n')
print('fp_cam_test.cfg: %d lines' % len(L))
