"""Generates the post-processing test scripts (tools/tests/post_*.cfg).

  post_toggle.cfg   every pass / mode on its own (r_post_disable per pass, every AA / upscaler /
                    tonemapper / debug view / quality preset / feedback effect): one screenshot
                    each into <out>/post_toggle/<name>.png. The runner checks 0 validation errors
                    and that every image is a plausible frame.
  post_perf.cfg     GPU timings per preset (post_bench 240 frames each).
  post_taa.cfg      TAA ghosting: identical scripted camera pan rendered with TAA and with no AA,
                    plus the still frame 12 and 200 frames after the pan stops.
"""
import os
import sys

out = sys.argv[1] if len(sys.argv) > 1 else 'C:/C/Game/build-alt/post_tests'
here = os.path.dirname(os.path.abspath(__file__))

# Every frame graph pass that can be skipped with r_post_disable (render.c + src/render/post).
PASSES = ['hiz', 'contact', 'gtao', 'gtao_temporal', 'gtao_upsample', 'ssgi', 'ssgi_temporal', 'ssgi_upsample', 'ssr',
          'ssr_temporal', 'vol_inject', 'vol_integrate', 'fog_apply', 'decals', 'scene_copy', 'transparent',
          'color_pyramid', 'depth_history', 'vm_prepass', 'viewmodel', 'taa', 'mb_tiles', 'mb_neighbor', 'mb_blur', 'dof_focus',
          'dof_coc', 'dof_down', 'dof_gather', 'dof_composite', 'exposure', 'bloom', 'flare', 'tonemap']

BASE = ['set r_post_preset 3', 'set r_ssgi 1', 'set r_dof 2', 'set r_lens_flare 0.8', 'set r_lens_dirt 0.6', 'set r_motion_blur 2',
        'set r_post_debug 0', 'set r_post_compare 0', 'set r_post_disable none', 'set r_upscaler 0', 'set r_aa 3', 'set r_tonemapper 1']


def shot(lines, name, wait=12):
    lines.append('wait %d' % wait)
    lines.append('screenshot %s/post_toggle/%s.png' % (out, name))
    lines.append('wait 2')


def toggle():
    L = ['// generated by gen_post_tests.py: every post pass / mode on its own', 'wait 40',
         'setpos -16.5 0.05 -22.5 70 -8', 'wait 30']
    L += BASE
    shot(L, 'all_on', 40)
    for p in PASSES:
        L.append('set r_post_disable %s' % p)
        shot(L, 'off_' + p)
    L.append('set r_post_disable none')
    for aa, n in ((0, 'aa_off'), (1, 'aa_fxaa'), (2, 'aa_smaa'), (3, 'aa_taa')):
        L.append('set r_aa %d' % aa)
        shot(L, n, 20)
    for up, n in ((1, 'up_taau'), (2, 'up_fsr1'), (3, 'up_fsr2_slot'), (4, 'up_dlss_slot')):
        L += ['set r_upscaler %d' % up, 'set r_upscale_ratio 0.6']
        shot(L, n, 30)
    L.append('set r_upscaler 0')
    L.append('set r_aa 2')
    L += ['set r_upscaler 2']
    shot(L, 'up_fsr1_smaa', 30)
    L += ['set r_upscaler 0', 'set r_aa 3']
    for tm, n in ((0, 'tm_aces'), (1, 'tm_agx'), (2, 'tm_neutral')):
        L.append('set r_tonemapper %d' % tm)
        shot(L, n)
    for v in range(1, 18):
        L.append('set r_post_debug %d' % v)
        shot(L, 'debug_%02d' % v, 6)
    L.append('set r_post_debug 0')
    L.append('set r_post_compare 1')
    shot(L, 'compare_split')
    L.append('set r_post_compare 0')
    for cb in (1, 2, 3):
        L.append('set r_colorblind %d' % cb)
        shot(L, 'colorblind_%d' % cb, 4)
    L.append('set r_colorblind 0')
    for p, n in ((0, 'preset_low'), (1, 'preset_medium'), (2, 'preset_high'), (3, 'preset_ultra')):
        L.append('set r_post_preset %d' % p)
        shot(L, n, 30)
    # Gameplay feedback.
    L += ['damage 75']
    shot(L, 'fb_damage_lowhealth', 6)
    L += ['post_flash 1']
    shot(L, 'fb_flash', 3)
    L += ['nightvision 1']
    shot(L, 'fb_nightvision', 30)
    L += ['nightvision 0', 'set r_fb_underwater 1']
    shot(L, 'fb_underwater', 10)
    L += ['set r_fb_underwater 0', 'set r_auto_exposure 0', 'set r_exposure 1']
    shot(L, 'manual_exposure', 10)
    L += ['set r_auto_exposure 1', 'set r_exposure 0', 'set r_lut assets/post/luts/teal_orange.cube']
    shot(L, 'lut_teal_orange', 10)
    L += ['set r_lut none', 'photomode 1']
    shot(L, 'photo_mode', 10)
    L += ['screenshot_hdr post_hdr_test %s/post_toggle/hdr_capture.png %s/post_toggle/hdr_capture.exr' % (out, out), 'wait 10', 'photomode 0']
    L += ['set r_render_scale 0.75']
    shot(L, 'render_scale_075', 30)
    L += ['set r_render_scale 1', 'wait 10', 'quit']
    return L


def perf():
    L = ['// generated by gen_post_tests.py: GPU ms per preset at 1920x1080', 'set r_mode 0', 'set r_width 1920', 'set r_height 1080',
         'vid_restart', 'wait 60', 'setpos -16.5 0.05 -22.5 70 -8', 'set r_post_profile 1', 'set r_vsync 0', 'set r_maxfps 0', 'wait 60']
    for p, n in ((0, 'low'), (1, 'medium'), (2, 'high'), (3, 'ultra')):
        L += ['set r_post_preset %d' % p, 'wait 90', 'post_bench 240 %s' % n, 'wait 250']
        L.append('screenshot %s/post_perf_%s.png' % (out, n))
        L.append('wait 2')
    L += ['quit']
    return L


def taa():
    # Pan 1.2 deg / frame for 50 frames, then hold still. Same commands for every AA mode.
    L = ['// generated by gen_post_tests.py: TAA ghosting check', 'wait 40', 'set r_motion_blur 0', 'set r_dof 0', 'set r_film_grain 0',
         'set r_chromatic 0', 'set r_auto_exposure 0', 'set r_exposure 0', 'setpos -16.5 0.05 -22.5 40 -8', 'wait 120']
    yaw = 40.0
    for i in range(50):
        yaw += 1.2
        L.append('setang %.2f -8' % yaw)
        L.append('wait 1')
        if i == 34:
            L.append('screenshot %s/taa_%%MODE%%_moving.png' % out)
    L.append('wait 12')
    L.append('screenshot %s/taa_%%MODE%%_stop12.png' % out)
    L.append('wait 200')
    L.append('screenshot %s/taa_%%MODE%%_still.png' % out)
    L += ['wait 3', 'quit']
    return L


def write(name, lines):
    with open(os.path.join(here, name), 'w', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')


write('post_toggle.cfg', toggle())
write('post_perf.cfg', perf())
t = taa()
for mode, aa in (('taa', 3), ('noaa', 0)):
    lines = [l.replace('%MODE%', mode) for l in t]
    lines.insert(2, 'set r_aa %d' % aa)
    write('post_taa_%s.cfg' % mode, lines)
print('written to', here)
