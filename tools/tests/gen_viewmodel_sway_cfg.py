#!/usr/bin/env python3
"""Writes tools/tests/viewmodel_sway.cfg (docs/FIRE_ANIM.md "Viewmodel sway"): the rifle in the dev
room hall, with cl_viewmodel_sway 0 and then 1: at rest, mid-turn (150 deg/s right, one setang per
frame), just after the turn stops (the overshoot), strafing right, walking forward, sprinting, and
turning while aimed. Each capture logs viewmodel_sway_info and takes vms_<on|off>_<name>.png.
Run from build/bin:
  ./deadground --test --nosound --log vms.log --script ../../tools/tests/viewmodel_sway.cfg
  python ../../tools/tests/viewmodel_sway_check.py vms.log"""
import os

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "viewmodel_sway.cfg")


def capture(lines, tag, name):
    lines.append(f"echo vms_capture {tag} {name}")
    lines.append("viewmodel_sway_info")
    lines.append(f"screenshot vms_{tag}_{name}.png")


def turn(lines, yaw0, frames, rate, pitch=0.0, capture_at=None, tag=None, name=None):
    yaw = yaw0
    for i in range(frames):
        yaw -= rate / 60.0   # right: yaw decreases
        lines.append(f"setang {yaw:.3f} {pitch:.2f}")
        if capture_at is not None and i == capture_at:
            capture(lines, tag, name)
        lines.append("wait 1")
    return yaw


def block(lines, on):
    tag = "on" if on else "off"
    lines.append(f"set cl_viewmodel_sway {1 if on else 0}")
    lines.append("setpos 0 0.05 22 0 0")
    lines.append("wait 60")
    capture(lines, tag, "rest")
    lines.append("wait 2")
    yaw = turn(lines, 0.0, 14, 150.0, capture_at=11, tag=tag, name="turn")
    lines.append("wait 4")
    capture(lines, tag, "overshoot")
    lines.append("wait 60")
    lines.append("+right")
    lines.append("wait 40")
    capture(lines, tag, "strafe")
    lines.append("wait 2")
    lines.append("-right")
    lines.append("wait 60")
    lines.append(f"setpos 0 0.05 22 {yaw:.3f} 0")
    lines.append("wait 30")
    lines.append("+forward")
    lines.append("wait 47")
    capture(lines, tag, "walk")
    lines.append("wait 2")
    lines.append("+sprint")
    lines.append("wait 45")
    capture(lines, tag, "sprint")
    lines.append("wait 2")
    lines.append("-sprint")
    lines.append("-forward")
    lines.append("wait 90")
    lines.append(f"setpos 0 0.05 22 0 0")
    lines.append("+aim")
    lines.append("wait 60")
    capture(lines, tag, "ads_rest")
    lines.append("wait 2")
    turn(lines, 0.0, 14, 150.0, capture_at=11, tag=tag, name="ads_turn")
    lines.append("-aim")
    lines.append("wait 60")


def main():
    lines = [
        "// Generated by gen_viewmodel_sway_cfg.py: see there.",
        "set r_maxfps 60",
        "set dev_fixed_fps 60",
        "wait 30",
        "inv_clear",
        "give rifle",
        "wield rifle",
        "wait 90",
    ]
    block(lines, False)
    block(lines, True)
    lines.append("echo vms_done")
    lines.append("quit")
    with open(OUT, "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", OUT, len(lines), "lines")


if __name__ == "__main__":
    main()
