"""Builds docs/items/ from a screenshot run (docs/ITEM_PIPELINE.md "Screenshots"): per item one before /
after sheet (the box-placeholder icon vs the detailed icon, plus the inspector views and, for weapons, the
first-person shots), and docs/items/README.md with the catalog table.

    python tools/tests/item_shots.py <shots> --views shaded,wear,matid --angles side,34 --before --fp > shots.cfg
    (run the game with shots.cfg; bake_icons writes the 'after' icons into assets/ui/icons)
    python tools/tests/item_docs.py <shots>
"""
import json
import os
import sys

from PIL import Image, ImageDraw

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
OUT = os.path.join(ROOT, "docs", "items")
TILE = 360


def load(path, size=None, crop_center=None):
    if not os.path.exists(path):
        return None
    im = Image.open(path).convert("RGBA")
    if crop_center:
        w, h = im.size
        cw, ch = int(w * crop_center), int(h * crop_center)
        im = im.crop(((w - cw) // 2, (h - ch) // 2, (w + cw) // 2, (h + ch) // 2))
    if size:
        im.thumbnail(size, Image.LANCZOS)
    return im


def on_bg(im, size, bg=(34, 36, 40, 255)):
    tile = Image.new("RGBA", size, bg)
    if im is not None:
        tile.alpha_composite(im, ((size[0] - im.size[0]) // 2, (size[1] - im.size[1]) // 2))
    return tile


def sheet(item_id, kind, shots, info):
    tiles = []
    icon_id = item_id if kind != "attachment" else item_id   # attachment items are att_<id> in the inventory too
    before = load(os.path.join(shots, "icons_before", "256", icon_id + ".png"), (TILE, TILE))
    after = load(os.path.join(ROOT, "assets", "ui", "icons", "256", icon_id + ".png"), (TILE, TILE))
    tiles.append(("before (box placeholder)", on_bg(before, (TILE, TILE))))
    tiles.append(("after (detailed mesh)", on_bg(after, (TILE, TILE))))
    for (label, name) in (("inspector", "shaded_side"), ("3/4", "shaded_34"), ("wear mask", "wear_34"), ("material ids", "matid_34")):
        im = load(os.path.join(shots, "%s_%s.png" % (item_id, name)), (TILE * 16 // 9, TILE), crop_center=0.7)
        if im is not None:
            tiles.append((label, on_bg(im, (im.size[0], TILE))))
    for (label, name) in (("first person before", "fp_before"), ("first person after", "fp_after"), ("ADS after", "ads_after")):
        im = load(os.path.join(shots, "%s_%s.png" % (item_id, name)), (TILE * 16 // 9, TILE))
        if im is not None:
            tiles.append((label, on_bg(im, (im.size[0], TILE))))
    cols = 3
    rows = (len(tiles) + cols - 1) // cols
    cw = max(t[1].size[0] for t in tiles)
    W, H = cw * cols, rows * (TILE + 24) + 40
    out = Image.new("RGB", (W, H), (22, 23, 26))
    d = ImageDraw.Draw(out)
    d.text((10, 10), "%s  (%s)   LOD 0/1/2: %s tris   parts %d" % (item_id, kind, " / ".join(str(t) for t in info["tris"]), info["parts"]), fill=(235, 235, 235))
    for i, (label, t) in enumerate(tiles):
        x, y = (i % cols) * cw, 40 + (i // cols) * (TILE + 24)
        out.paste(t.convert("RGB"), (x + (cw - t.size[0]) // 2, y + 20))
        d.text((x + 8, y + 4), label, fill=(190, 190, 190))
    os.makedirs(OUT, exist_ok=True)
    path = os.path.join(OUT, item_id + ".jpg")
    out.save(path, quality=84, optimize=True)
    return os.path.relpath(path, OUT)


def main(argv):
    shots = argv[1]
    sys.path.insert(0, os.path.join(ROOT, "tools", "validate_item"))
    import validate_item as V
    cat = json.load(open(os.path.join(ROOT, "assets", "items", "catalog.json")))["items"]
    rows = []
    for item_id in sorted(cat, key=lambda k: ({"weapon": 0, "attachment": 1}.get(cat[k]["kind"], 2), k)):
        m = V.read_dgim(os.path.join(ROOT, "assets", "items", "meshes", item_id + ".dgim"))
        tris = [0, 0, 0]
        for p in m["parts"]:
            for l in range(p["lod_count"]):
                tris[l] += p["inn"][l] // 3
        info = dict(tris=tris, parts=len(m["parts"]))
        img = sheet(item_id, cat[item_id]["kind"], shots, info)
        socks = sorted(s["name"] for s in m["sockets"])
        rows.append("| [%s](%s) | %s | %s | %d / %d / %d | %d | %s | %s |" % (item_id, img, cat[item_id]["kind"] + (" (cheap)" if cat[item_id].get("tier") == "cheap" else ""),
                                                                         cat[item_id]["path"], tris[0], tris[1], tris[2], len(m["parts"]), ", ".join(m["mats"]), ", ".join(socks)))
    md = ["# Detailed items: before / after", "",
          "Generated by `tools/tests/item_docs.py` from a screenshot run (docs/ITEM_PIPELINE.md). Each sheet shows the box placeholder icon",
          "(before), the detailed mesh icon (after), inspector views (shaded, wear mask, material ids) and, for weapons, first person.",
          "Rendered with the software Vulkan driver (lavapipe), dev room, 11:00 clear sky.", "",
          "| Item | Kind | Path | LOD 0 / 1 / 2 tris | Parts | Materials | Sockets |", "|---|---|---|---|---|---|---|"] + rows
    open(os.path.join(OUT, "README.md"), "w").write("\n".join(md) + "\n")
    print("item_docs: %d sheets in docs/items" % len(rows))


if __name__ == "__main__":
    main(sys.argv)
