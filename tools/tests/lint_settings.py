#!/usr/bin/env python3
"""Settings audit lint (docs/SETTINGS_AUDIT.md). Fails (exit 1) when:
  * a cvar registration in src/ has no classification flag, or more than one (CVAR_EDITABLE /
    CVAR_TIER / CVAR_LOCKED; CVAR_RULE only with CVAR_LOCKED), or a TIER / LOCKED cvar (not a host
    rule) is still CVAR_ARCHIVE (it would be saved to config.cfg);
  * assets/ui/settings_audit.json lacks a registered cvar, disagrees with its flag, or names a cvar
    that no longer exists;
  * assets/render/consistency.json names a cvar that isn't CVAR_LOCKED (or has no "why");
  * a player-visible Settings page (src/ui/screens/scr_settings.c, outside `if (dev_ui())` blocks
    and the Graphics > Debug page) shows a TIER / LOCKED cvar;
  * the Graphics tab isn't Engine Fidelity, Era, Look, then the Display and Comfort groups, or the
    HUD tab doesn't start with the crosshair;
  * the table in docs/SETTINGS_AUDIT.md is out of date (--write regenerates it).
Run: python3 tools/tests/lint_settings.py [--write]"""
import json, os, re, sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import lint_commands as LC  # noqa: E402

CALL = re.compile(r"(?<![\w.>])(cvar_reg_bool|cvar_reg_int|cvar_reg_float|cvar_reg_string|cvar_reg)\s*\(")
FLAGS_ARG = {"cvar_reg_bool": 2, "cvar_reg_string": 2, "cvar_reg_int": 4, "cvar_reg_float": 4, "cvar_reg": 3}
CLASS = {"CVAR_EDITABLE": "EDITABLE", "CVAR_TIER": "TIER", "CVAR_LOCKED": "LOCKED"}
DOC = os.path.join(ROOT, "docs", "SETTINGS_AUDIT.md")
BEGIN, END = "<!-- settings_audit:begin (generated by tools/tests/lint_settings.py --write) -->", "<!-- settings_audit:end -->"
# Player pages of scr_settings.c: what a release build shows.
PLAYER_FUNCS = ["graphics_header", "fidelity_section", "era_row", "look_section", "display_section", "comfort_section", "tab_graphics", "crosshair_sections",
                "tab_hud", "tab_controls", "tab_audio", "tab_character", "tab_phone"]


def split_args(s, i):
    spans, depth, j, st = [], 0, i, i
    while j < len(s):
        c = s[j]
        if c == '"':
            j += 1
            while s[j] != '"':
                j += 2 if s[j] == "\\" else 1
        elif c in "([{":
            depth += 1
        elif c in ")]}":
            if depth == 0:
                spans.append((st, j))
                return spans
            depth -= 1
        elif c == "," and depth == 0:
            spans.append((st, j))
            st = j + 1
        j += 1
    return spans


def registrations():
    """(rel, line, name, class, flags tokens, desc) of every literal cvar registration in src/."""
    out = []
    for dp, _, files in os.walk(os.path.join(ROOT, "src")):
        for f in sorted(files):
            if not f.endswith(".c"):
                continue
            p = os.path.join(dp, f)
            rel = os.path.relpath(p, ROOT).replace("\\", "/")
            src = open(p, encoding="utf-8", errors="replace").read()
            for m in CALL.finditer(src):
                spans = split_args(src, m.end())
                first = src[spans[0][0]:spans[0][1]]
                nm = re.match(r'\s*"([^"]*)"', first)
                if not nm or "const char *name" in first:
                    continue
                k = FLAGS_ARG[m.group(1)]
                expr = src[spans[k][0]:spans[k][1]] if k < len(spans) else ""
                toks = [t.strip() for t in expr.split("|") if t.strip()]
                descs = LC.STR.findall(src[spans[-1][0]:spans[-1][1]])
                out.append((rel, src.count("\n", 0, m.start()) + 1, nm.group(1), toks, descs[-1] if descs else ""))
    return out


def class_of(toks):
    cls = [CLASS[t] for t in toks if t in CLASS]
    if len(cls) != 1:
        return None, cls
    c = cls[0]
    if c == "LOCKED" and "CVAR_RULE" in toks:
        c = "LOCKED+RULE"
    return c, cls


def strip_dev_blocks(body):
    # Drop `if (dev_ui()) { ... }` blocks (a dev build's developer rows).
    out, i = [], 0
    while True:
        j = body.find("if (dev_ui())", i)
        if j < 0:
            out.append(body[i:])
            return "".join(out)
        out.append(body[i:j])
        k = body.find("{", j)
        depth, m = 0, k
        while m < len(body):
            if body[m] == "{":
                depth += 1
            elif body[m] == "}":
                depth -= 1
                if depth == 0:
                    break
            m += 1
        i = m + 1


def func_body(src, name):
    m = re.search(r"\n(?:static )?[\w ]+\b%s\s*\([^)]*\)\s*\{" % re.escape(name), src)
    if not m:
        return None
    i, depth = m.end() - 1, 0
    for j in range(i, len(src)):
        if src[j] == "{":
            depth += 1
        elif src[j] == "}":
            depth -= 1
            if depth == 0:
                return src[i:j + 1]
    return None


def feature_cvars():
    src = open(os.path.join(ROOT, "src/render/fidelity/fidelity.c"), encoding="utf-8").read()
    return {m.group(1): m.group(2) for m in re.finditer(r"\[(FF_\w+)\]\s*=\s*\{\s*\"[^\"]+\",\s*\"([^\"]+)\"", src)}


def table(regs, audit, cats):
    rows = []
    for rel, line, name, toks, desc in regs:
        cls, _ = class_of(toks)
        a = audit.get(name, {})
        locked = {"EDITABLE": "no", "TIER": "yes (Engine Fidelity writes)", "LOCKED": "yes", "LOCKED+RULE": "yes (+ host rule)"}.get(cls, "?")
        rows.append((["EDITABLE", "TIER", "LOCKED", "LOCKED+RULE"].index(cls) if cls else 9, LC.category_of(cats, name) or "?", name,
                     "| `%s` | %s | %s | %s | %s | %s |" % (name, LC.category_of(cats, name) or "?", cls or "?", a.get("ui", "?"), locked, a.get("reason", "?").replace("|", "/"))))
    rows.sort(key=lambda r: (r[0], r[1], r[2]))
    n = {}
    for rel, line, name, toks, desc in regs:
        c = class_of(toks)[0] or "?"
        n[c] = n.get(c, 0) + 1
    head = ["%d cvars: %d EDITABLE, %d TIER, %d LOCKED, %d LOCKED + host rule. \"UI\" \"—\": in no settings tab." % (len(regs), n.get("EDITABLE", 0), n.get("TIER", 0), n.get("LOCKED", 0), n.get("LOCKED+RULE", 0)), "",
            "| Cvar | Category | Class | UI | Locked in release | Reason |", "|---|---|---|---|---|---|"]
    return "\n".join(head + [r[3] for r in rows]) + "\n"


def main():
    fails = []
    regs, seen = [], set()
    for r in registrations():
        if r[2] in seen:
            continue
        seen.add(r[2])
        regs.append(r)
    classes = {}
    for rel, line, name, toks, desc in regs:
        cls, found = class_of(toks)
        if cls is None:
            fails.append("%s:%d: %s: %s classification flag%s (CVAR_EDITABLE / CVAR_TIER / CVAR_LOCKED, docs/SETTINGS_AUDIT.md)" %
                         (rel, line, name, "no" if not found else "%d" % len(found), "" if not found else "s"))
            continue
        if "CVAR_RULE" in toks and "CVAR_LOCKED" not in toks:
            fails.append("%s:%d: %s: CVAR_RULE without CVAR_LOCKED" % (rel, line, name))
        if cls in ("TIER", "LOCKED") and ("CVAR_ARCHIVE" in toks or "A" in toks):
            fails.append("%s:%d: %s: a %s cvar must not be CVAR_ARCHIVE (never saved to config.cfg)" % (rel, line, name, cls))
        classes[name] = cls
    audit = json.load(open(os.path.join(ROOT, "assets/ui/settings_audit.json"), encoding="utf-8"))["cvars"]
    for name, cls in classes.items():
        a = audit.get(name)
        if not a:
            fails.append("assets/ui/settings_audit.json: no entry for %s (class, ui, reason)" % name)
        elif a.get("class") != cls:
            fails.append("assets/ui/settings_audit.json: %s is %s there, %s in its registration" % (name, a.get("class"), cls))
        elif len(a.get("reason", "")) < 12:
            fails.append("assets/ui/settings_audit.json: %s needs a reason" % name)
    for name in audit:
        if name not in classes:
            fails.append("assets/ui/settings_audit.json: %s is not a registered cvar" % name)
    cons = json.load(open(os.path.join(ROOT, "assets/render/consistency.json"), encoding="utf-8"))["values"]
    for name, e in cons.items():
        if not classes.get(name, "").startswith("LOCKED"):
            fails.append("assets/render/consistency.json: %s is %s (needs CVAR_LOCKED)" % (name, classes.get(name, "not registered")))
        if len(e.get("why", "")) < 8:
            fails.append("assets/render/consistency.json: %s needs a \"why\"" % name)
    # Settings UI.
    ui = open(os.path.join(ROOT, "src/ui/screens/scr_settings.c"), encoding="utf-8").read()
    ff = feature_cvars()
    for fn in PLAYER_FUNCS:
        body = func_body(ui, fn)
        if body is None:
            fails.append("scr_settings.c: no %s()" % fn)
            continue
        body = strip_dev_blocks(body)
        names = set(re.findall(r'(?:row_\w+_cvar|rid)\(\s*(?:c,\s*"[^"]*",\s*)?"([a-z][a-z0-9_]+)"', body))
        names |= {ff[f] for f in re.findall(r"\b(FF_\w+)\b", body) if f in ff}
        for n in sorted(names):
            if n in classes and classes[n] != "EDITABLE":
                fails.append("scr_settings.c %s(): shows %s, a %s cvar (players can't change it, docs/SETTINGS_AUDIT.md)" % (fn, n, classes[n]))
    g = func_body(ui, "tab_graphics") or ""
    calls = re.findall(r"\b(\w+)\(c\);", g)
    want = ["graphics_header", "fidelity_section", "era_row", "look_section", "display_section", "comfort_section"]
    if calls != want:
        fails.append("scr_settings.c tab_graphics(): %s, want %s" % (calls, want))
    for fn, title in (("display_section", "Display"), ("comfort_section", "Comfort")):
        secs = re.findall(r'section\(c, "([^"]+)"\)', func_body(ui, fn) or "")
        if secs != [title]:
            fails.append("scr_settings.c %s(): groups %s, want [%s]" % (fn, secs, title))
    hud = re.findall(r"\b(\w+)\(c\);|section\(c, \"([^\"]+)\"\)", func_body(ui, "tab_hud") or "")
    if not hud or hud[0][0] != "crosshair_sections":
        fails.append("scr_settings.c tab_hud(): the crosshair comes first")
    # The doc's table.
    cats = LC.load_categories()
    gen = table(regs, audit, cats)
    doc = open(DOC, encoding="utf-8").read() if os.path.exists(DOC) else ""
    if BEGIN in doc and END in doc:
        cur = doc[doc.index(BEGIN) + len(BEGIN):doc.index(END)].strip("\n") + "\n"
        if "--write" in sys.argv and cur != gen:
            doc = doc[:doc.index(BEGIN) + len(BEGIN)] + "\n" + gen + doc[doc.index(END):]
            open(DOC, "w", encoding="utf-8", newline="\n").write(doc)
            print("lint_settings: docs/SETTINGS_AUDIT.md table regenerated")
        elif cur != gen:
            fails.append("docs/SETTINGS_AUDIT.md: the table is out of date (python3 tools/tests/lint_settings.py --write)")
    else:
        fails.append("docs/SETTINGS_AUDIT.md: no generated table markers")
    for f in fails:
        print("lint_settings: " + f)
    print("lint_settings: %d cvars, %d failure(s)" % (len(regs), len(fails)))
    return 1 if fails else 0


if __name__ == "__main__":
    sys.exit(main())
